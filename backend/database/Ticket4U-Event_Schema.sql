DROP TABLE IF EXISTS public.seats;

-- Phụ thuộc vào Zones
DROP TABLE IF EXISTS public.zones;

-- Phụ thuộc vào Events
DROP TABLE IF EXISTS public.events;

-- Phụ thuộc vào Venue, Categories, EventTypes
DROP TABLE IF EXISTS public.categories;

DROP TABLE IF EXISTS public.venue;

DROP TABLE IF EXISTS public.wards;

DROP TABLE IF EXISTS public.provinces;

-- ==================================
-- Location Tables					|
-- ==================================
CREATE TABLE
	IF NOT EXISTS public.provinces (
		id INTEGER NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
		name_vi VARCHAR(50) NOT NULL,
		name_en VARCHAR(50) NOT NULL,
		PRIMARY KEY (id)
	);

CREATE TABLE
	IF NOT EXISTS public.wards (
		id INTEGER NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
		name_vi VARCHAR(50) NOT NULL,
		name_en VARCHAR(50) NOT NULL,
		province_id INTEGER,
		CONSTRAINT ward_fk_province FOREIGN KEY (province_id) REFERENCES public.provinces (id),
		PRIMARY KEY (id)
	);

CREATE TABLE
	IF NOT EXISTS public.venue (
		id UUID PRIMARY KEY NOT NULL DEFAULT gen_random_uuid (),
		name_vi VARCHAR(50) NOT NULL,
		name_en VARCHAR(50) NOT NULL,
		address_line VARCHAR(255) NOT NULL,
		ward_id INTEGER,
		CONSTRAINT venue_fk_ward FOREIGN KEY (ward_id) REFERENCES public.wards (id)
	);

-- ==============================
-- Event Related Tables			|
-- ==============================
CREATE TABLE
	IF NOT EXISTS public.categories (
		id INTEGER NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
		name VARCHAR(255) NOT NULL,
		PRIMARY KEY (id)
	);

CREATE TABLE
	IF NOT EXISTS public.events (
		id UUID PRIMARY KEY NOT NULL DEFAULT gen_random_uuid (),
		name VARCHAR(255),
		organizer_id UUID, -- references to the table organizers of the users service
		category_id INTEGER,
		venue_id UUID,
		start_date TIMESTAMPTZ,
		end_date TIMESTAMPTZ,
		status varchar(50) CHECK (
			status IN ('PLANNED', 'ONGOING', 'FINISHED', 'CANCELLED')
		),
		created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
		updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
		CONSTRAINT event_fk_category FOREIGN KEY (category_id) REFERENCES public.categories (id) ON UPDATE NO ACTION ON DELETE NO ACTION,
		CONSTRAINT event_fk_venue FOREIGN KEY (venue_id) REFERENCES public.venue (id)
	);

CREATE TABLE
	IF NOT EXISTS public.zones (
		id UUID PRIMARY KEY NOT NULL DEFAULT gen_random_uuid (),
		event_id UUID,
		name VARCHAR(255),
		is_standing BOOLEAN DEFAULT FALSE,
		capacity INTEGER DEFAULT 0,
		quantity_sold INTEGER DEFAULT 0 CHECK (quantity_sold >= 0),
		price DECIMAL(10, 2),
		CONSTRAINT zone_fk_event FOREIGN KEY (event_id) REFERENCES public.events (id) ON UPDATE NO ACTION ON DELETE NO ACTION
	);

CREATE TABLE
	IF NOT EXISTS public.seats (
		id UUID PRIMARY KEY NOT NULL DEFAULT gen_random_uuid (),
		zone_id UUID,
		name VARCHAR(255),
		row_name VARCHAR(5),
		col_name VARCHAR(5),
		seat_code VARCHAR(5),
		status varchar(50) CHECK (status IN ('AVAILABLE', 'BOOKED', 'HOLD')),
		price_override DECIMAL(10, 2), -- nếu muốn 1 ghế nào đó đặc biệt giá khác trong 1 zone
		CONSTRAINT seat_fk_zone FOREIGN KEY (zone_id) REFERENCES public.zones (id) ON UPDATE NO ACTION ON DELETE NO ACTION
	);