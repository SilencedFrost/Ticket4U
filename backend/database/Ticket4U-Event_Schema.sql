DROP TABLE IF EXISTS public.seats;
DROP TABLE IF EXISTS public.zones;
DROP TABLE IF EXISTS public.event_sessions;
DROP TABLE IF EXISTS public.event_categories;
DROP TABLE IF EXISTS public.events;
DROP TABLE IF EXISTS public.venues;
DROP TABLE IF EXISTS public.categories;

-- Table: categories
CREATE TABLE IF NOT EXISTS public.categories (
	id 		INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	name 	VARCHAR(255) NOT NULL UNIQUE
);

-- Table: venues
CREATE TABLE IF NOT EXISTS public.venues (
	id 				UUID PRIMARY KEY,
	name varchar(64) NOT NULL,
	address_line 	VARCHAR(255) NOT NULL,
	longitude 		DECIMAL(10, 7) NOT NULL,
	latitude 		DECIMAL(10, 7) NOT NULL,
	layout 	JSONB,
	image_url 		TEXT,
	created_at 		TIMESTAMPTZ NOT NULL,
	updated_at 		TIMESTAMPTZ
);

-- Table: events
-- status: editing, premier ,selling, paused (stop selling),ongoing ,finished ,cancelled
-- category_id: null because we can create event without category, and assign category later
CREATE TABLE IF NOT EXISTS public.events (
	id 						UUID PRIMARY KEY,
	name 					VARCHAR(255) NOT NULL UNIQUE,
	organizer_id 			UUID NOT NULL,

	address_line 			VARCHAR(255),
	status 					VARCHAR(50) NOT NULL,
	banner_url 				TEXT NOT NULL,

	created_at 				TIMESTAMPTZ NOT NULL,
	updated_at 				TIMESTAMPTZ,
	cancelled_at 			TIMESTAMPTZ,

	about_vi 				TEXT,
	about_en				TEXT,
	terms_and_conditions 	TEXT,
	policy_refund 			TEXT,
	seating_plan_image_url 	TEXT,

	venue_id 				UUID,
    layout                  JSONB,

	longitude 	DECIMAL(10, 7),
	latitude 	DECIMAL(10, 7),

	CONSTRAINT event_fk_venue FOREIGN KEY (venue_id)
		REFERENCES public.venues (id)
);

-- Table: event_sessions
-- This table is created to support events that have multiple performances with different schedules.
-- status: scheduled, ongoing, finished, cancelled
CREATE TABLE IF NOT EXISTS public.event_sessions (
    id          UUID PRIMARY KEY,
    event_id    UUID NOT NULL,
    start_date  TIMESTAMPTZ NOT NULL,
    end_date    TIMESTAMPTZ NOT NULL,
    status      VARCHAR(50) NOT NULL,
    name        VARCHAR(255) NOT NULL,
	created_at TIMESTAMPTZ NOT NULL,

	CONSTRAINT session_fk_event FOREIGN KEY (event_id)
		REFERENCES public.events (id)
);

--Table: event_categories
--Junction table for N-N relationship between events and categories
CREATE TABLE IF NOT EXISTS public.event_categories (
	event_id UUID NOT NULL,
	category_id INTEGER NOT NULL,

	PRIMARY KEY (event_id, category_id),

	CONSTRAINT fk_event FOREIGN KEY (event_id) REFERENCES public.events (id) ON DELETE CASCADE,
	CONSTRAINT fk_category FOREIGN KEY (category_id) REFERENCES public.categories (id) ON DELETE CASCADE
);

-- Table: zones
-- purchase_limit: null means no limit
-- perks: Save the perks of each zone in JSON format, for example: ["Free drink", "Lightstick", "Fansign"]
CREATE TABLE IF NOT EXISTS public.zones (
	id 					UUID PRIMARY KEY,
	session_id 			UUID NOT NULL,
	name 				VARCHAR(255) NOT NULL,
	is_standing 		BOOLEAN NOT NULL,
	capacity 			INTEGER,
	purchase_limit      INTEGER,
	
	price 				DECIMAL(10, 2) NOT NULL,

	description_vi 		TEXT,
	description_en 		TEXT,
	gift_image_url 		VARCHAR(512),
    perks 				JSONB,
    created_at 			TIMESTAMPTZ NOT NULL,
	updated_at 			TIMESTAMPTZ,

	CONSTRAINT zone_fk_session FOREIGN KEY (session_id)
		REFERENCES public.event_sessions (id)
);

-- Table: seats
-- price_override: if you want to set a different price for a specific seat in a zone
CREATE TABLE IF NOT EXISTS public.seats (
	id 				UUID PRIMARY KEY,
	zone_id 		UUID NOT NULL,
	name 			VARCHAR(255),
	row_name 		VARCHAR(5),
	col_name 		VARCHAR(5),
	seat_code 		VARCHAR(20),
	price_override 	DECIMAL(10, 2),

	CONSTRAINT seat_fk_zone FOREIGN KEY (zone_id)
		REFERENCES public.zones (id)
);