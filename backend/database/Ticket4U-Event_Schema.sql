DROP TABLE IF EXISTS public.seats;
DROP TABLE IF EXISTS public.zones;
DROP TABLE IF EXISTS public.events;
DROP TABLE IF EXISTS public.categories;

DROP TABLE IF EXISTS public.venue;
DROP TABLE IF EXISTS public.wards;
DROP TABLE IF EXISTS public.provinces;

-- Table: categories
CREATE TABLE IF NOT EXISTS public.categories (
	id 		INTEGER NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	name 	VARCHAR(255) NOT NULL UNIQUE,
	PRIMARY KEY (id)
);

-- Table: events
-- organizer_id references to the table organizers of the users service
-- status: editing, premier ,selling, paused (stop selling),ongoing ,finished ,cancelled
CREATE TABLE IF NOT EXISTS public.events (
	id 						UUID PRIMARY KEY NOT NULL DEFAULT gen_random_uuid (),
	name 					VARCHAR(255) NOT NULL UNIQUE,
	organizer_id 			UUID NOT NULL,
	category_id 			INTEGER,
	address_line 			VARCHAR(255),
	start_date 				TIMESTAMPTZ,
	end_date 				TIMESTAMPTZ,
	status 					varchar(50) CHECK (
								status IN ('PLANNED', 'ONGOING', 'FINISHED', 'CANCELLED')
							),
	banner_url 				TEXT,
	description 			TEXT,

	created_at 				TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
	updated_at 				TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
	cancelled_at 			TIMESTAMPTZ,

	about_vi 				TEXT,
	about_en				TEXT,
	terms_and_conditions 	TEXT,
	policy_refund 			TEXT,
	seating_plan_image_url 	TEXT,

	CONSTRAINT event_fk_category FOREIGN KEY (category_id)
		REFERENCES public.categories (id) ON UPDATE NO ACTION ON DELETE CASCADE
);

-- Table: zones
-- purchase_limit: null means no limit
-- perks: Save the perks of each zone in JSON format, for example: ["Free drink", "Lightstick", "Fansign"]
CREATE TABLE IF NOT EXISTS public.zones (
	id 					UUID PRIMARY KEY NOT NULL DEFAULT gen_random_uuid (),
	event_id 			UUID NOT NULL,
	name 				VARCHAR(255) NOT NULL,
	is_standing 		BOOLEAN DEFAULT FALSE,
	capacity 			INTEGER DEFAULT 0,
	quantity_sold 		INTEGER DEFAULT 0 CHECK (quantity_sold >= 0),
	purchase_limit 		INTEGER NULL,
	price 				DECIMAL(10, 2) NOT NULL,

	description 		TEXT,
	gift_image_url 		VARCHAR(512),
    perks 				JSONB,
    created_at 			TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
	updated_at 			TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

	CONSTRAINT zone_fk_event FOREIGN KEY (event_id)
		REFERENCES public.events (id) ON UPDATE NO ACTION ON DELETE CASCADE
);

-- Table: seats
-- price_override: if you want to set a different price for a specific seat in a zone
CREATE TABLE IF NOT EXISTS public.seats (
	id 				UUID PRIMARY KEY NOT NULL DEFAULT gen_random_uuid (),
	zone_id 		UUID,
	name 			VARCHAR(255),
	row_name 		VARCHAR(5),
	col_name 		VARCHAR(5),
	seat_code 		VARCHAR(20),
	status 			varchar(50) CHECK (status IN ('AVAILABLE', 'BOOKED', 'HOLD')),
	price_override 	DECIMAL(10, 2),
	CONSTRAINT seat_fk_zone FOREIGN KEY (zone_id)
		REFERENCES public.zones (id) ON UPDATE NO ACTION ON DELETE CASCADE
);